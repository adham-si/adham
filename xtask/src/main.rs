fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    match args.next().as_deref() {
        Some("contracts") => generate_contracts()?,
        Some(cmd) => {
            eprintln!("Unknown xtask command: {cmd}");
            std::process::exit(1);
        }
        None => {
            println!("Usage: cargo xtask <contracts>");
        }
    }
    Ok(())
}

